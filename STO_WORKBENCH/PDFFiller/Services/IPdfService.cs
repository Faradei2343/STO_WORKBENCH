using STO_WORKBENCH.Core;

namespace STO_WORKBENCH.PDFFiller.Services
{
    // Интерфейс сервиса обработки PDF-документов (сервисных листов).
    // Описывает основной конвейер заполнения (ProcessPdfAsync), чтение дат из
    // фиксированных областей первой страницы и поиск координат текстового маркера,
    // который служит точкой отсчёта для всех надписей.
    // Реализация — PdfService (используются две библиотеки: Spire.PDF — для поиска маркера,
    // iTextSharp — для извлечения текста и наложения новых надписей).
    public interface IPdfService
    {
        // Основной метод: заполняет один PDF-файл (ФИО исполнителя, оценка, дата, заявитель)
        // и сохраняет результат в выходную папку.
        // fileName — имя файла без пути (папки входа/выхода берутся из settings);
        // settings — текущие настройки приложения (пути и данные исполнителя);
        // options — пользовательские опции обработки (своя дата / только месяц-год / свой заявитель).
        // Возвращает true при успехе; false — при любой ошибке
        // (пользователь уже уведомлён об ошибке через IMessageService).
        Task<bool> ProcessPdfAsync(string fileName, AppSettings settings, PdfProcessingOptions options);

        // Читает "дату поступления заявки" из фиксированной области первой страницы PDF.
        // filePath — полный путь к файлу.
        // Возвращает дату или null, если область не содержит корректной даты.
        DateTime? GetReceiptDate(string filePath);

        // Читает "контрольную дату" из фиксированной области первой страницы PDF.
        // filePath — полный путь к файлу.
        // Возвращает дату или null, если область не содержит корректной даты.
        DateTime? GetControlDate(string filePath);

        // Ищет по всем страницам документа текст-маркер "(ФИО)" и возвращает координаты
        // первого найденного вхождения — это якорь, относительно которого вычисляются
        // позиции всех проставляемых надписей.
        // filePath — полный путь к файлу.
        // Возвращает координаты найденного маркера или null, если маркер отсутствует.
        PointF? GetMarkerCoordinates(string filePath);
    }
}
